#!/bin/sh
# Writes deepsecrets.code-workspace at the repository root (git-ignored): a multi-root workspace with this repository
# and, when /workspaces/dsbench holds a checkout (DSBENCH_REPO_DIR in .devcontainer/.env), dsbench beside it. The two
# stay separate repositories with their own settings; the workspace only puts them in one window. post-create.sh runs
# this on every container creation; run it again by hand after adding or removing the dsbench checkout.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
dsbench=/workspaces/dsbench
out="$root/deepsecrets.code-workspace"

if [ -f "$dsbench/pyproject.toml" ]; then
    extra=",
        { \"name\": \"dsbench\", \"path\": \"$dsbench\" }"
    with="with dsbench"
else
    extra=""
    with="without dsbench (no checkout at $dsbench)"
fi

cat > "$out" <<EOF
// Generated by .devcontainer/workspace.sh when the container is created; it is rewritten then, so put settings in
// each repository's .vscode/settings.json instead. Open it with File > Open Workspace from File.
{
    "folders": [
        { "name": "deepsecrets", "path": "." }$extra
    ],
    "settings": {
        // the private agent docs are a repository of their own at docs/private, two levels down
        "git.repositoryScanMaxDepth": 2
    }
}
EOF
echo "workspace.sh: wrote $out $with"
